import type { PageBlock } from "../../shared/types";

// Real body content for the 25 "Wegoinn DB" seed items (see
// `worker/routes/admin.ts` for the matching title/category/tags/description
// metadata). Deliberately contains no attachment placeholders — file
// uploads are a separate feature (worker/routes/attachments.ts) and stay
// empty until someone attaches a real file through the UI — and no real
// phone numbers, passwords, vehicle plates, customer names or reservation
// numbers. Wherever that kind of value would go, the text says "추후 입력"
// or "관리자 입력 필요" instead, exactly as specified.
let counter = 0;
function id(): string {
  counter += 1;
  return `seed-${counter}-${Date.now().toString(36)}`;
}

function p(text: string): PageBlock {
  return { id: id(), type: "paragraph", text };
}
function h3(text: string): PageBlock {
  return { id: id(), type: "heading3", text };
}
function li(text: string): PageBlock {
  return { id: id(), type: "bulleted_list_item", text };
}
function num(text: string): PageBlock {
  return { id: id(), type: "numbered_list_item", text };
}
function table(rows: string[][]): PageBlock {
  return { id: id(), type: "table", rows };
}
function callout(text: string): PageBlock {
  return { id: id(), type: "callout", text };
}

export interface ContentSeedNode {
  /** Must exactly match an existing page title (top-level title from SEED_PAGES in admin.ts). */
  title: string;
  blocks?: PageBlock[];
  children?: ContentSeedNode[];
}

